let currentLanguage = 'fr';
const WHATSAPP_NUMBER = '213551858534'; // Numéro WhatsApp du Salon El Jida


const navToggle = document.querySelector('.nav-toggle');
const navMenu = document.querySelector('.nav-menu');
const navLinks = document.querySelectorAll('.nav-menu a');
const header = document.querySelector('.site-header');

function setMenuTop() {
  if (!header) return;
  const top = header.getBoundingClientRect().bottom;
  document.documentElement.style.setProperty('--menu-top', `${Math.round(top + 10)}px`);
}

navToggle?.addEventListener('click', () => {
  const isOpen = navMenu.classList.toggle('open');
  navToggle.classList.toggle('active', isOpen);
  navToggle.setAttribute('aria-expanded', String(isOpen));
  setMenuTop();
});

navLinks.forEach((link) => {
  link.addEventListener('click', () => {
    navMenu.classList.remove('open');
    navToggle?.classList.remove('active');
    navToggle?.setAttribute('aria-expanded', 'false');
  });
});

function updateWhatsAppUrls(lang) {
  const msg = translations[lang].whatsappMsg || 'Bonjour Éclat Beauty Salon, je veux réserver un rendez-vous.';
  const encodedMsg = encodeURIComponent(msg);
  const waUrl = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodedMsg}`;
  document.querySelectorAll('.whatsapp-link').forEach((link) => {
    link.href = waUrl;
  });
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLanguage = lang;
  const dict = translations[lang];

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  document.querySelectorAll('.lang-dropdown a').forEach((option) => {
    const optLang = option.dataset.lang;
    option.classList.toggle('active', optLang === lang);
  });

  const langLabel = document.querySelector('.lang-code');
  if (langLabel) {
    langLabel.textContent = lang.toUpperCase();
  }

  updateWhatsAppUrls(lang);
  try {
    localStorage.setItem('eclat-language', lang);
  } catch (e) {
    console.warn('localStorage non disponible', e);
  }

  const languageSwitcher = document.querySelector('.language-switcher');
  const langButton = document.querySelector('.lang-button');
  languageSwitcher?.classList.remove('open');
  langButton?.setAttribute('aria-expanded', 'false');
}

function initLanguageEvents() {
  const languageSwitcher = document.querySelector('.language-switcher');
  const langButton = document.querySelector('.lang-button');

  langButton?.addEventListener('click', (event) => {
    event.stopPropagation();
    const isOpen = languageSwitcher?.classList.toggle('open');
    langButton.setAttribute('aria-expanded', String(isOpen));
  });

  document.querySelectorAll('.lang-dropdown a').forEach((option) => {
    option.addEventListener('click', (event) => {
      event.preventDefault();
      event.stopPropagation();
      const selectedLang = option.dataset.lang || 'fr';
      setLanguage(selectedLang);
    });
  });

  document.addEventListener('click', () => {
    languageSwitcher?.classList.remove('open');
    langButton?.setAttribute('aria-expanded', 'false');
  });

  try {
    const storedLang = localStorage.getItem('eclat-language');
    if (storedLang && translations[storedLang]) {
      setLanguage(storedLang);
    }
  } catch (e) {}
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLanguageEvents);
} else {
  initLanguageEvents();
}



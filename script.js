// ---------- FLOATING BUBBLES ANIMATION ----------
function initBubblesAnimation() {
  let container = document.getElementById('bubbles');
  if (!container) {
    container = document.createElement('div');
    container.id = 'bubbles';
    document.body.prepend(container);
  }
  container.innerHTML = '';
  const count = 20;
  for (let i = 0; i < count; i++) {
    const bubble = document.createElement('span');
    const size = Math.random() * 45 + 12;
    const left = Math.random() * 100;
    const duration = Math.random() * 12 + 8;
    const delay = -Math.random() * 15;
    const opacity = Math.random() * 0.45 + 0.25;

    bubble.style.width = `${size}px`;
    bubble.style.height = `${size}px`;
    bubble.style.left = `${left}%`;
    bubble.style.animationDuration = `${duration}s`;
    bubble.style.animationDelay = `${delay}s`;
    bubble.style.opacity = opacity;

    container.appendChild(bubble);
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initBubblesAnimation);
} else {
  initBubblesAnimation();
}

/* ---------- Scroll Progress Bar ---------- */
(function(){
  const progress = document.getElementById('progress');
  if (!progress) return;
  window.addEventListener('scroll', () => {
    const y = window.scrollY;
    const h = document.body.scrollHeight - window.innerHeight;
    progress.style.width = (h > 0 ? (y / h * 100) : 0) + '%';
  });
})();
